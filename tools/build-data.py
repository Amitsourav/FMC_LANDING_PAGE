"""Generate medical-data.js from the Medical Loan Build & SEO Specification markdown.

Usage: python3 -I tools/build-data.py /path/to/FundMyCampus_Medical_Loan_Build_and_SEO_Specification.md

Reads Appendices A-D (QHEI snapshot, NMC medical, DCI dental, owner-confirmed additions)
and writes a compact public dataset. No lender identity is written to the output.
"""
import csv, json, os, re, sys

STATE_FIX = {
    'Andaman And Nicobar Islands': 'Andaman and Nicobar Islands',
    'Chattisgarh': 'Chhattisgarh',
    'Jammu And Kashmir': 'Jammu and Kashmir',
    'Jammu & Kashmir': 'Jammu and Kashmir',
    'Daman & Diu': 'Daman and Diu',
    'Orissa': 'Odisha',
    'Pondicherry': 'Puducherry',
    'Uttrakhand': 'Uttarakhand',
    'The Dadra and Nagar Haveli and Daman and Diu': 'Dadra and Nagar Haveli and Daman and Diu',
    'The Dadra and Nagar': 'Dadra and Nagar Haveli and Daman and Diu',
}

def state(s):
    return STATE_FIX.get(s, s)

def tables(lines):
    """Yield (appendix letter, header, rows) for appendix tables A-D."""
    out, cur, header, rows = {}, None, None, []
    for line in lines:
        m = re.match(r'^## Appendix ([A-G]) ', line)
        if m:
            if cur and header:
                out[cur] = (header, rows)
            cur, header, rows = m.group(1), None, []
            continue
        if cur and line.startswith('|') and not re.match(r'^\|\s*-', line):
            cells = [c.strip() for c in line.strip().strip('|').split('|')]
            if header is None:
                header = cells
            elif len(cells) == len(header):
                rows.append(cells)
    if cur and header:
        out[cur] = (header, rows)
    return out

def dash(s):
    return s.replace('–', '-').replace('—', '-')

def main(path):
    t = tables(open(path, encoding='utf-8').read().split('\n'))
    qhei = {}
    for row in t['A'][1]:
        _, aishe, name, st, mgmt, rate = row
        qhei[aishe] = {'a': aishe, 'n': name, 's': state(st), 'm': mgmt, 'r': dash(rate)}
    for row in t['D'][1]:
        aishe, name, st = row[0], row[1], row[2]
        qhei[aishe] = {'a': aishe, 'n': name, 's': state(st), 'x': 1}

    # Reviewed college <-> QHEI links that the spec's match column misses (same institution only,
    # never a parent university). See tools/qhei-links.csv.
    extra = {}
    links_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'qhei-links.csv')
    for row in csv.DictReader(open(links_path, encoding='utf-8')):
        assert row['aishe'] in qhei, 'unknown AISHE in qhei-links.csv: ' + row['aishe']
        assert row['aishe'] not in extra.values(), 'AISHE linked twice: ' + row['aishe']
        extra[row['college_id']] = row['aishe']

    linked = set()
    records = []
    for row in t['B'][1]:
        iid, name, st, univ, mbbs, pg, match = row
        match = match if match in qhei else extra.get(iid, match)
        r = {'i': iid, 'n': name, 's': state(st), 'd': 'M', 'u': univ,
             'mb': 1 if mbbs == 'Yes' else 0, 'pg': 1 if pg == 'Yes' else 0}
        if match in qhei:
            r['a'] = match
            linked.add(match)
        records.append(r)
    for row in t['C'][1]:
        iid, name, st, mgmt, seats, match = row
        match = match if match in qhei else extra.get(iid, match)
        r = {'i': iid, 'n': name, 's': state(st), 'd': 'D'}
        if mgmt:
            r['m'] = mgmt
        if seats:
            r['st'] = int(seats)
        if match in qhei:
            r['a'] = match
            linked.add(match)
        records.append(r)
    for aishe, q in qhei.items():
        if aishe in linked:
            continue
        r = {'i': 'qhei-' + aishe, 'n': q['n'], 's': q['s'], 'd': 'Q', 'a': aishe}
        if q.get('m'):
            r['m'] = q['m']
        records.append(r)

    # Attach scheme evidence to linked records (rate formula / addition flag)
    for r in records:
        q = qhei.get(r.get('a'))
        if q:
            if q.get('r'):
                r['r'] = q['r']
            if q.get('x'):
                r['x'] = 1

    meta = {
        'qheiSnapshot': '2026-09-04', 'qheiCount': len(t['A'][1]),
        'additionsConfirmed': '2026-10-14', 'additionsCount': len(t['D'][1]),
        'nmcAsOf': '2026-10-12', 'nmcCount': len(t['B'][1]),
        'dciSeatYear': '2025-26', 'dciCount': len(t['C'][1]),
        'pickerCount': len(records),
        'reviewedLinks': len(extra),
        'dataVersion': 'FMC-MED-DATA-2026-10-23',
    }
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'medical-data.js')
    with open(out, 'w', encoding='utf-8') as f:
        f.write('/* Generated by tools/build-data.py — do not edit by hand. */\n')
        f.write('var MED_META = ' + json.dumps(meta, ensure_ascii=False) + ';\n')
        f.write('var MED_INSTITUTIONS = ' + json.dumps(records, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print(meta)

if __name__ == '__main__':
    main(sys.argv[1])
